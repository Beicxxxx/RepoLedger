CANONICAL_HEADER = (
    "| id | name | status | parent | order | anchor | supersedes | date | legacy | note |\n"
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
OWNER_HEADER = (
    "| id | name | status | parent | order | owner | legacy | supersedes | date | note |\n"
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n")
TYPES = """
[types.TASK]
allowed_statuses = ["BACKLOG", "READY", "IN_PROGRESS", "BLOCKED", "DONE", "DROPPED"]
description = "Work items"

[types.ISSUE]
allowed_statuses = ["OPEN", "INVESTIGATING", "RESOLVED", "WONT_FIX"]

[types.MODEL]
allowed_statuses = ["DRAFT", "IN_FORCE", "SUPERSEDED"]
"""
DOT = " · "
LINK = "[`docs/proposal.md`](../proposal.md)"
DEFAULT_STATUS = {"TASK": "READY", "ISSUE": "OPEN", "MODEL": "DRAFT"}


def cell(value):
    return value.replace("\\", "\\\\").replace("|", "\\|")


def row(entity_id, name, *, status=None, parent="", order=None, anchor="docs/proposal.md",
        supersedes="", date="2026-09-01", legacy="", note="", layout="canonical"):
    type_name, serial = entity_id.rsplit("-", 1)
    status = status or DEFAULT_STATUS[type_name]
    order = serial if order is None else str(order)
    if layout == "owner":
        cells = [entity_id, name, status, parent, order, anchor, legacy, supersedes, date, note]
    else:
        cells = [entity_id, name, status, parent, order, anchor, supersedes, date, legacy, note]
    return "| " + " | ".join(cell(value) for value in cells) + " |\n"


def make_project(root, rows, *, index="", independent_order=False, layout="canonical", git=False):
    root.mkdir(parents=True, exist_ok=True)
    if git:
        subprocess.run(["git", "init", str(root)], check=True, capture_output=True)
    config = ('[ledger]\nschema_version = "1.0"\nregistry_path = ".ledger/ENTITY_REGISTRY.md"\n'
              f"independent_order = {'true' if independent_order else 'false'}\n" + TYPES)
    if index:
        config += "\n[index]\n" + index
    (root / "ledger.toml").write_text(config, encoding="utf-8")
    (root / "docs").mkdir(exist_ok=True)
    (root / "docs" / "proposal.md").write_text("# Proposal\n", encoding="utf-8")
    registry = root / ".ledger" / "ENTITY_REGISTRY.md"
    registry.parent.mkdir(exist_ok=True)
    header = OWNER_HEADER if layout == "owner" else CANONICAL_HEADER
    registry.write_text("<!-- schema: 1.0 -->\n# Entity Registry\n\n" + header + "".join(rows),
                        encoding="utf-8")
    if git:
        subprocess.run(["git", "-C", str(root), "add", "."], check=True, capture_output=True)
    return root


def index(capsys, root, *extra):
    capsys.readouterr()
    code = main(["index", "--root", str(root), "--json", *extra])
    return code, json.loads(capsys.readouterr().out)


def generate(capsys, root, out="docs/index"):
    code, report = index(capsys, root, "--out", str(root / out))
    assert code == 0, report
    return root / out


def text(path):
    return path.read_text(encoding="utf-8")


def entity_headings(page):
    return [line for line in page.splitlines() if line.startswith("##")]


def fields_of(page, entity_id):
    """Return the compact field line of an entity rendered as a heading or a bullet."""
    lines = page.splitlines()
    for number, line in enumerate(lines):
        if line.startswith("##") and line.split(" ", 2)[1] == entity_id:
            assert lines[number + 1] == ""
            return lines[number + 2]
        if line.lstrip(" ").startswith(f"- {entity_id} "):
            return line.lstrip(" ").split(DOT, 1)[1]
    raise AssertionError(f"{entity_id} is not rendered")


def snapshot(directory):
    if not directory.exists():
        return None
    return {path.name: path.read_bytes() for path in sorted(directory.iterdir())}


def fingerprint(root):
    return hashlib.sha256((root / ".ledger" / "ENTITY_REGISTRY.md").read_bytes()).hexdigest()[:12]


def header(root):
    return (f"<!-- registry: .ledger/ENTITY_REGISTRY.md; registry-sha256: {fingerprint(root)}; "
            "generated by repo-ledger index; do not edit by hand -->")


