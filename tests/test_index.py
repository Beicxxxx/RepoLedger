def test_entities_deeper_than_level_six_continue_as_nested_bullets(tmp_path, capsys):
    rows = [row("TASK-1", "Level 1")]
    rows += [row(f"TASK-{n}", f"Level {n}", parent=f"TASK-{n - 1}") for n in range(2, 9)]
    rows += [row("TASK-9", "Deep sibling", parent="TASK-5"),
             row("TASK-10", "Deeper sibling", parent="TASK-6")]
    page = text(generate(capsys, make_project(tmp_path / "p", rows)) / "TASK.md")
    lines = page.splitlines()

    assert entity_headings(page) == ["## TASK-1 Level 1", "### TASK-2 Level 2", "#### TASK-3 Level 3",
                                     "##### TASK-4 Level 4", "###### TASK-5 Level 5"]
    bullets = [line for line in lines if line.lstrip(" ").startswith("- ")]
    assert [line.split(DOT)[0] for line in bullets] == [
        "- TASK-6 Level 6", "  - TASK-7 Level 7", "    - TASK-8 Level 8",
        "  - TASK-10 Deeper sibling", "- TASK-9 Deep sibling"]
    assert bullets[0] == DOT.join(["- TASK-6 Level 6", "status: READY", "date: 2026-09-01", f"anchor: {LINK}"])
    # One tight list that follows the level-6 heading block.
    start = lines.index(bullets[0])
    assert start > lines.index("###### TASK-5 Level 5")
    assert lines[start:start + len(bullets)] == bullets
    assert lines[start - 1] == ""


def test_cross_type_parent_is_shown_on_both_pages(tmp_path, capsys):
    rows = [row("TASK-1", "Parent task"), row("TASK-2", "Other task"),
            row("ISSUE-1", "Child issue", parent="TASK-1"), row("ISSUE-2", "Plain issue"),
            row("ISSUE-3", "Nested issue", parent="ISSUE-1")]
    out = generate(capsys, make_project(tmp_path / "p", rows))
    issues, tasks = text(out / "ISSUE.md"), text(out / "TASK.md")

    assert entity_headings(issues) == ["## ISSUE-1 Child issue", "### ISSUE-3 Nested issue",
                                       "## ISSUE-2 Plain issue"]
    assert fields_of(issues, "ISSUE-1").endswith(DOT + "parent: TASK-1 Parent task")
    assert "parent:" not in fields_of(issues, "ISSUE-3")

    assert entity_headings(tasks) == ["## TASK-1 Parent task", "## TASK-2 Other task"]
    lines = tasks.splitlines()
    children = lines.index("children of other types: ISSUE-1 Child issue")
    assert lines.index("## TASK-1 Parent task") < children < lines.index("## TASK-2 Other task")


